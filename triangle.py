def area(a, h):
    """
    Рассчитывает площадь треугольника.

    Args:
        a: Длина основания
        h: Высота, проведённая к основанию

    Returns:
        Значение площади
    """
    return a * h / 2  


def perimeter(a, b, c):
    """
    Рассчитывает периметр треугольника.

    Args:
        a: длина первой стороны
        b: длина второй стороны
        c: длина третей стороны

    Returns:
        Значение периметра
    """
    return a + b + c 









