def area(a, b):
    """
    Рассчитывает площадь прямоугольника.

    Args:
        a: длина первой стороны
        b: длина второй стороны

    Returns:
        Значение площади
    """
    return a * b


def perimeter(a, b):
    """
    Рассчитывает периметр прямоугольника.

    Args:
        a: длина первой стороны
        b: длина второй стороны

    Returns:
        Значение периметра
    """
    return (a + b) * 2
