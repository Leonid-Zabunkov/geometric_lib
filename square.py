
def area(a):
    """
    Рассчитывает площадь квадрата.

    Args:
        a: Сторона квадрата

    Returns:
        Значение площади
    """
    return a * a


def perimeter(a):
    """
    Рассчитывает периметр квадрата.

    Args:
        a: Сторона квадрата

    Returns:
        Значение периметра
    """
    return 4 * a
